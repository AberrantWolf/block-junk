//! Runtime mod commands enter the same construction service as player requests.
use bevy::prelude::*;
use block_junk_scripting::{
    commands::{Command, CommandReceipt, CommandResult, InventoryBank, TransferDirection},
    state::StateScope,
};

#[derive(bevy::ecs::system::SystemParam)]
pub(crate) struct ModCommandWorld<'w, 's> {
    construction: crate::construction::ConstructionService<'w>,
    chunks: Query<
        'w,
        's,
        (
            &'static mut crate::voxel::Chunk,
            &'static mut crate::voxel::ChunkEntities,
        ),
    >,
    commands: Commands<'w, 's>,
    edits: MessageWriter<'w, crate::protocol::CellEdit>,
    effects: ResMut<'w, crate::server::PendingTerrainEffects>,
    spaces: ResMut<'w, crate::space_identity::SpaceIdentities>,
    published_spaces: Option<Res<'w, crate::live_spaces::PublishedSpaces>>,
    map: Res<'w, crate::voxel::ChunkMap>,
    blocks: Res<'w, crate::blocks::BlockRegistry>,
    placements: ResMut<'w, crate::placements::Placements>,
    items: Res<'w, crate::items::ItemRegistry>,
    recipes: Res<'w, crate::recipes::RecipeRegistry>,
    facilities: crate::facility_inventory::FacilityService<'w>,
    kinds: Query<'w, 's, &'static crate::npc::NpcKind>,
    kind_registry: Res<'w, crate::npc_registry::NpcKindRegistry>,
    npcs: Query<'w, 's, &'static crate::npc::NpcId>,
    actor_poses:
        Query<'w, 's, (Entity, &'static crate::protocol::AvatarPose), With<crate::protocol::Actor>>,
    npc_ids: ResMut<'w, crate::npc::NpcIdAllocator>,
    interactions: ResMut<'w, crate::interactables::InteractionClaims>,
    interaction_jobs: ResMut<'w, crate::facility_interactions::FacilityInteractions>,
    facility_access: Option<Res<'w, crate::facility_access::FacilityAccess>>,
    preset: Option<Res<'w, crate::scripting::SelectedWorld>>,
    tools: Query<'w, 's, &'static mut crate::protocol::EquippedTool>,
    brains: Query<'w, 's, (&'static crate::npc::Brain, Has<crate::npc::BrainDisabled>)>,
    carriers: Query<
        'w,
        's,
        (
            Entity,
            &'static crate::npc::NpcId,
            &'static mut crate::protocol::Carrying,
            &'static crate::protocol::AvatarPose,
        ),
    >,
}

pub(crate) fn execute_batches(mods: Res<crate::scripting::ServerMods>, mut world: ModCommandWorld) {
    // A fixed snapshot prevents callbacks generated by this work from re-entering
    // this tick. The outbox also bounds work retained between ticks.
    let batches: Vec<_> = {
        let mut queue = mods.0.commands.batches.lock().unwrap();
        let count = queue.len().min(8);
        queue.drain(..count).collect()
    };
    for batch in batches {
        let outcome = (|| {
            mods.0.validate_cause(batch.cause)?;
            if !mods
                .0
                .mods
                .iter()
                .any(|m| m.manifest.id == batch.mod_id && !m.disabled)
            {
                return Err("command owner is disabled or missing".into());
            }
            let mut construction = world.construction.stage();
            let mut interaction_jobs = world.interaction_jobs.clone();
            let mut interaction_claims = world.interactions.clone();
            let mut placements = world.placements.clone();
            let mut npc_ids = world.npc_ids.clone();
            let mut spawning = std::collections::BTreeMap::<u64, (String, Vec3)>::new();
            let mut removing = std::collections::BTreeMap::<u64, Entity>::new();
            let mut terrain = crate::terrain_transaction::TerrainTransaction::default();
            let mut receipts = Vec::new();
            let mut resolved_spaces = std::collections::BTreeSet::new();
            let mut carried = std::collections::BTreeMap::new();
            let mut facilities = crate::facility_inventory::FacilityTransaction::default();
            mods.0.state_transaction(&batch.mod_id, |state| {
                let base = |cell| {
                    let (coord, local) = crate::voxel::world_to_chunk(cell);
                    let entity = *world.map.0.get(&coord)?;
                    let (chunk, sidecar) = world.chunks.get(entity).ok()?;
                    Some((chunk.get(local), sidecar.get(cell), chunk.revision))
                };
                for command in &batch.commands {
                    match command {
                        Command::StartInteraction {placement_id,revision,npc_id,slot_key,action,approach} => {
                            if npc_ids.retired.contains(npc_id) || construction.actor_has_job(*npc_id) || facilities.actor_has_job(*npc_id,&world.facilities) || world.construction.actor_is_hauling(crate::npc::NpcId(*npc_id)) {return Err("interaction actor already assigned or retired".into());}
                            let placement=placements.records.get(&block_junk_mod_api::architecture::PlacementId(*placement_id)).filter(|record|record.active && record.revision==*revision).ok_or("interaction placement missing or stale")?;
                            let position=if let Some((_,position))=spawning.get(npc_id) {*position} else {
                                let (entity,_,_,pose)=world.carriers.iter().find(|(_,id,_,_)|id.0==*npc_id).ok_or("interaction actor missing")?;
                                let (brain,disabled)=world.brains.get(entity).map_err(|_|"actor has no behavior")?;
                                if disabled || (!matches!(brain.goal,crate::npc::Goal::Idle) && interaction_jobs.active_for(*npc_id).is_none()) {return Err("interaction actor busy or disabled".into());}
                                pose.translation
                            };
                            if approach.iter().any(|v|v.unsigned_abs()>1_000_064) {return Err("interaction approach outside world bounds".into());}
                            let foot=IVec3::from_array(*approach);
                            if !position.is_finite() || position.distance(foot.as_vec3()+Vec3::splat(0.5))>2. {return Err("actor is not at the authored approach".into());}
                            for (cell,solid) in [(foot,false),(foot+IVec3::Y,false),(foot-IVec3::Y,true)] {
                                let (block,_,_)=terrain.read(cell,&base).ok_or("interaction approach geometry unavailable")?;
                                if (!block.is_empty() && !world.blocks.def(block).flags.walkable_boundary)!=solid {return Err("interaction approach is obstructed or unsupported".into());}
                            }
                            let slot_id=block_junk_mod_api::architecture::UseSlotId {placement:placement.id,key:slot_key.clone()};
                            crate::facility_access::require_usable_approach(
                                world.facility_access.as_deref().ok_or("facility access service unavailable")?,
                                placement.revision,
                                &slot_id,
                                &world.preset.as_deref().ok_or("selected world unavailable")?.0.movement_profile,
                                foot,
                            )?;
                            let job=interaction_jobs.prepare(crate::facility_interactions::InteractionRequest {placement,slot_key,action,actor:block_junk_mod_api::authority::ReservationOwner::Npc{id:*npc_id},controller:block_junk_mod_api::authority::ReservationOwner::Behavior{mod_id:batch.mod_id.clone(),registration_id:batch.behavior.clone()},cause:batch.cause,approach:foot},&world.blocks,&mut interaction_claims)?;
                            receipts.push(CommandReceipt::Job{job});
                        }
                        Command::ReadInteractionJob {job_id}=>receipts.push(CommandReceipt::Job{job:interaction_jobs.jobs.records.get(job_id).cloned().ok_or("interaction job missing or retired")?}),
                        Command::ReadInteractionJobs{after_id,limit}=>{
                            if !(1..=64).contains(limit) {return Err("job page limit must be 1 through 64".into());}
                            let (jobs,has_more)=interaction_jobs.jobs.owned_jobs(&batch.mod_id,*after_id,usize::from(*limit));receipts.push(CommandReceipt::Jobs{jobs,has_more});
                        }
                        Command::AcknowledgeInteractionJob{job_id,revision}=>{
                            let job=interaction_jobs.jobs.records.get(job_id).ok_or("interaction job missing")?;
                            if !matches!(&job.controller,block_junk_mod_api::authority::ReservationOwner::Behavior{mod_id,..} if mod_id==&batch.mod_id) {return Err("only the controlling mod may acknowledge this result".into());}
                            interaction_jobs.jobs.acknowledge(*job_id,*revision)?;
                        }
                        Command::StartConstruction {project_id,revision,npc_id} => {
                            if interaction_jobs.active_for(*npc_id).is_some() {return Err("actor has an interaction job".into());}
                            if npc_ids.retired.contains(npc_id) || world.construction.actor_is_hauling(crate::npc::NpcId(*npc_id)) || facilities.actor_has_job(*npc_id,&world.facilities) { return Err("construction actor unavailable or already assigned".into()); }
                            let anchor = construction.project_anchor(*project_id,*revision)?;
                            let position = if let Some((_,position))=spawning.get(npc_id) {*position} else {
                                let (entity,_,_,pose)=world.carriers.iter().find(|(_,id,_,_)|id.0==*npc_id).ok_or("construction actor missing")?;
                                let (brain,disabled)=world.brains.get(entity).map_err(|_|"construction actor has no behavior")?;
                                if disabled || !(matches!(brain.goal,crate::npc::Goal::Idle) || matches!(brain.goal,crate::npc::Goal::Working {project_token,..} if project_token==(*project_id,*revision))) {return Err("construction actor busy or disabled".into());}
                                pose.translation
                            };
                            if !position.is_finite() || position.distance(anchor.as_vec3()+Vec3::splat(0.5))>crate::protocol::INTERACT_REACH { return Err("construction actor cannot reach project".into()); }
                            let job=construction.prepare_job(*project_id,*revision,*npc_id,block_junk_mod_api::authority::ReservationOwner::Behavior {mod_id:batch.mod_id.clone(),registration_id:batch.behavior.clone()},batch.cause)?;
                            receipts.push(CommandReceipt::Job {job});
                        }
                        Command::ReadConstructionJob {job_id} => receipts.push(CommandReceipt::Job {job:construction.read_job(*job_id)?}),
                        Command::ReadConstructionJobs {after_id,limit} => {
                            if !(1..=64).contains(limit) {return Err("job page limit must be 1 through 64".into());}
                            let (jobs,has_more)=construction.owned_jobs(&batch.mod_id,*after_id,usize::from(*limit));
                            receipts.push(CommandReceipt::Jobs {jobs,has_more});
                        }
                        Command::AcknowledgeConstructionJob {job_id,revision} => construction.acknowledge_job(&batch.mod_id,*job_id,*revision)?,
                        Command::StartCraft {placement_id,revision,npc_id,order_id,order_revision} => {
                            if interaction_jobs.active_for(*npc_id).is_some() {return Err("actor has an interaction job".into());}
                            if npc_ids.retired.contains(npc_id) {return Err("craft actor retired".into());}
                            if construction.actor_has_job(*npc_id) {return Err("craft actor has a construction job".into());}
                            if world.construction.actor_is_hauling(crate::npc::NpcId(*npc_id)) {return Err("craft actor already has a hauling assignment".into());}
                            let record=placements.records.get(&block_junk_mod_api::architecture::PlacementId(*placement_id)).filter(|record|record.active && record.revision==*revision).ok_or("craft facility missing or stale")?;
                            let anchor=IVec3::from_array(record.anchor);
                            let def=world.blocks.def(world.blocks.slot_of(&record.definition).ok_or("craft facility definition missing")?);
                            let station=crate::craft_stations::StationDefView {tag:def.station_tag.clone().ok_or("facility is not a crafting station")?,tier:def.station_tier};
                            let (position,tool)=if let Some((_,position))=spawning.get(npc_id) {(*position,None)} else {
                                let (entity,_,_,pose)=world.carriers.iter().find(|(_,id,_,_)|id.0==*npc_id).ok_or("craft actor unavailable")?;
                                let (brain,disabled)=world.brains.get(entity).map_err(|_|"craft actor has no behavior")?;
                                if disabled || !(matches!(brain.goal,crate::npc::Goal::Idle) || matches!(brain.goal,crate::npc::Goal::CraftingAtStation {station_cell} if station_cell==anchor)) {return Err("craft actor is busy or disabled".into());}
                                (pose.translation,world.tools.get(entity).ok().and_then(|tool|tool.item))
                            };
                            if !position.is_finite() || position.distance(anchor.as_vec3()+Vec3::splat(0.5))>crate::protocol::INTERACT_REACH {return Err("craft actor cannot reach station".into());}
                            let job=facilities.prepare_craft(&world.facilities,crate::facility_inventory::CraftRequest {cause:batch.cause,anchor,actor:block_junk_mod_api::authority::ReservationOwner::Npc {id:*npc_id},controller:block_junk_mod_api::authority::ReservationOwner::Behavior {mod_id:batch.mod_id.clone(),registration_id:batch.behavior.clone()},order_id:*order_id,order_revision:*order_revision,tool,station:&station,recipes:&world.recipes})?;
                            receipts.push(CommandReceipt::Job {job});
                        }
                        Command::AcknowledgeCraftJob {job_id,revision}=> {facilities.acknowledge_job(&batch.mod_id,*job_id,*revision,&world.facilities)?;}
                        Command::ReadCraftJobs {after_id,limit}=> {
                            if !(1..=64).contains(limit) {return Err("job page limit must be 1 through 64".into());}
                            let (jobs,has_more)=facilities.owned_jobs(&batch.mod_id,*after_id,usize::from(*limit),&world.facilities);
                            receipts.push(CommandReceipt::Jobs {jobs,has_more});
                        }
                        Command::ReadCraftJob { job_id } => {
                            receipts.push(CommandReceipt::Job {
                                job: facilities.read_job(*job_id, &world.facilities)?,
                            });
                        }
                        Command::SpawnNpc { npc_kind, position } => {
                            if world.kind_registry.get(npc_kind).is_none() {
                                return Err("unknown NPC kind".into());
                            }
                            let position = Vec3::from_array(*position);
                            if !position.is_finite() || position.abs().max_element() > 1_000_000. {
                                return Err("invalid NPC position".into());
                            }
                            let centre =
                                position - Vec3::Y * crate::physics::EYE_OFFSET_FROM_CENTRE;
                            let min = (centre - crate::physics::PLAYER_HALF_EXTENTS)
                                .floor()
                                .as_ivec3();
                            let max = (centre + crate::physics::PLAYER_HALF_EXTENTS
                                - Vec3::splat(0.0001))
                            .floor()
                            .as_ivec3();
                            for x in min.x..=max.x {
                                for y in min.y..=max.y {
                                    for z in min.z..=max.z {
                                        let cell=IVec3::new(x,y,z);
                                        let (slot, entry, _) = terrain
                                            .read(cell, &base)
                                            .ok_or("NPC spawn geometry unavailable")?;
                                        let def=world.blocks.def(slot);
                                        if !def.structure.portals.is_empty() {
                                            let anchor=match entry {Some(crate::voxel::EntryKind::Ghost{anchor})=>anchor,_=>cell};
                                            let (_,entry,_)=terrain.read(anchor,&base).ok_or("NPC spawn portal anchor unavailable")?;
                                            let (orientation,open)=match entry {Some(crate::voxel::EntryKind::Anchor{orientation,portal_open})=>(orientation,portal_open),_=>(Default::default(),None)};
                                            let lo=centre-crate::physics::PLAYER_HALF_EXTENTS;
                                            let hi=centre+crate::physics::PLAYER_HALF_EXTENTS;
                                            if world.blocks.collision[slot.0 as usize][orientation as usize].at(anchor,open).iter().any(|bounds|bounds.min.cmplt(hi).all()&&bounds.max.cmpgt(lo).all()) {return Err("NPC spawn portal is obstructed".into());}
                                            continue;
                                        }
                                        if !slot.is_empty()
                                            && !def.flags.walkable_boundary
                                        {
                                            return Err("NPC spawn body is obstructed".into());
                                        }
                                    }
                                }
                            }
                            let id = npc_ids.allocate()?;
                            spawning.insert(id.0, (npc_kind.clone(), position));
                            receipts.push(CommandReceipt::Npc {
                                npc_id: id.0,
                                revision: 1,
                            });
                        }
                        Command::RemoveNpc { npc_id, revision } => {
                            if *revision != 1 {
                                return Err("NPC revision stale".into());
                            }
                            npc_ids.retire(*npc_id)?;
                            interaction_jobs.interrupt_actor(*npc_id,"actor removed",&mut interaction_claims);
                            facilities.release_actor(crate::npc::NpcId(*npc_id), &world.facilities);
                            construction.release_actor(crate::npc::NpcId(*npc_id));
                            if spawning.remove(npc_id).is_some() {
                                continue;
                            }
                            let (entity, _, carry, pose) = world
                                .carriers
                                .iter()
                                .find(|(_, id, _, _)| id.0 == *npc_id)
                                .ok_or("NPC unavailable")?;
                            let (_, carry) = carried.entry(*npc_id).or_insert((entity, *carry));
                            if carry.item.is_none() && carry.count != 0 {
                                return Err("NPC has invalid carried inventory".into());
                            }
                            if let Some(item) = carry.item {
                                facilities.return_item(
                                    pose.translation.floor().as_ivec3(),
                                    world.items.id_of(item).clone(),
                                    carry.count,
                                );
                            }
                            *carry = Default::default();
                            if let Ok(tool) = world.tools.get(entity)
                                && let Some(item) = tool.item
                            {
                                facilities.return_item(
                                    pose.translation.floor().as_ivec3(),
                                    world.items.id_of(item).clone(),
                                    1,
                                );
                            }

                            removing.insert(*npc_id, entity);
                        }
                        Command::QueueCraft {
                            placement_id,
                            revision,
                            recipe,
                            quantity,
                        } => {
                            let record = placements
                                .records
                                .get(&block_junk_mod_api::architecture::PlacementId(
                                    *placement_id,
                                ))
                                .filter(|record| record.active && record.revision == *revision)
                                .ok_or("craft facility missing or stale")?;
                            let anchor = IVec3::from_array(record.anchor);
                            let block = world
                                .blocks
                                .slot_of(&record.definition)
                                .ok_or("craft facility definition missing")?;
                            let def = world.blocks.def(block);
                            let station = crate::craft_stations::StationDefView {
                                tag: def
                                    .station_tag
                                    .clone()
                                    .ok_or("facility is not a crafting station")?,
                                tier: def.station_tier,
                            };
                            let id = facilities.queue_order(
                                anchor,
                                &world.facilities,
                                &world.recipes,
                                &station,
                                recipe,
                                *quantity,
                            )?;
                            receipts.push(CommandReceipt::CraftOrder {
                                placement_id: *placement_id,
                                order_id: id,
                                revision: 1,
                            });
                        }
                        Command::CancelCraft {
                            placement_id,
                            revision,
                            order_id,
                            order_revision,
                        } => {
                            let record = placements
                                .records
                                .get(&block_junk_mod_api::architecture::PlacementId(
                                    *placement_id,
                                ))
                                .filter(|record| record.active && record.revision == *revision)
                                .ok_or("craft facility missing or stale")?;
                            facilities.cancel_order(
                                IVec3::from_array(record.anchor),
                                &world.facilities,
                                *order_id,
                                *order_revision,
                            )?;
                        }
                        Command::TransferFacility {
                            placement_id,
                            revision,
                            npc_id,
                            item,
                            count,
                            bank,
                            direction,
                        } => {
                            if *count == 0 {
                                return Err("inventory transfer count must be positive".into());
                            }
                            let record = placements
                                .records
                                .get(&block_junk_mod_api::architecture::PlacementId(
                                    *placement_id,
                                ))
                                .filter(|record| record.active && record.revision == *revision)
                                .ok_or("inventory facility missing or stale")?;
                            let anchor = IVec3::from_array(record.anchor);
                            let (block, _, _) = terrain
                                .read(anchor, &base)
                                .ok_or("facility geometry unavailable")?;
                            if world.blocks.id_of(block) != &record.definition {
                                return Err("facility geometry changed".into());
                            }
                            let def = world.blocks.def(block);
                            let (entity, _, inventory, pose) = world
                                .carriers
                                .iter()
                                .find(|(_, id, _, _)| id.0 == *npc_id)
                                .ok_or("inventory actor unavailable")?;
                            if !pose.translation.is_finite()
                                || pose
                                    .translation
                                    .distance(anchor.as_vec3() + Vec3::splat(0.5))
                                    > crate::protocol::INTERACT_REACH
                            {
                                return Err("inventory actor cannot reach facility".into());
                            }
                            let kind = world
                                .kinds
                                .get(entity)
                                .ok()
                                .and_then(|kind| world.kind_registry.get(&kind.0))
                                .ok_or("inventory actor has no validated kind")?;
                            let item_slot = world
                                .items
                                .slot_of(&item.clone().into())
                                .ok_or("unknown inventory item")?;
                            let (_, inventory) =
                                carried.entry(*npc_id).or_insert((entity, *inventory));
                            if matches!(direction, TransferDirection::Deposit)
                                && (inventory.item != Some(item_slot) || inventory.count < *count)
                            {
                                return Err("inventory actor does not hold requested bundle".into());
                            }
                            let banks = facilities.at(anchor, &world.facilities);
                            let accepted =
                                match (bank, direction) {
                                    (InventoryBank::Storage, TransferDirection::Deposit)
                                        if def.container.is_some() =>
                                    {
                                        banks.storage.transfer_from_carry(
                                            inventory,
                                            *count,
                                            def.container.as_ref().expect("validated container"),
                                            &world.items,
                                        )
                                    }
                                    (InventoryBank::Storage, TransferDirection::Withdraw)
                                        if def.container.is_some() =>
                                    {
                                        banks.storage.transfer_to_carry(
                                            inventory,
                                            item_slot,
                                            *count,
                                            kind.carry_capacity,
                                        )
                                    }
                                    (InventoryBank::Crafting, TransferDirection::Deposit)
                                        if def.station_tag.is_some() =>
                                    {
                                        banks.crafting.transfer_from_carry(inventory, *count)
                                    }
                                    (InventoryBank::Crafting, TransferDirection::Withdraw)
                                        if def.station_tag.is_some() =>
                                    {
                                        banks.crafting.transfer_to_carry(
                                            inventory,
                                            item_slot,
                                            *count,
                                            kind.carry_capacity,
                                        )
                                    }
                                    _ => return Err(
                                        "facility does not provide the requested inventory bank"
                                            .into(),
                                    ),
                                };
                            if accepted != *count {
                                return Err("inventory transfer lacks stock or capacity".into());
                            }
                            receipts.push(CommandReceipt::InventoryTransfer {
                                placement_id: *placement_id,
                                npc_id: *npc_id,
                                item: item.clone(),
                                count: *count,
                            });
                        }
                        Command::ReadSpace {space_id}=>{
                            let record=world.spaces.records.get(&crate::space_identity::SpaceId(*space_id)).ok_or("space identity not found")?;
                            let geometry=world.published_spaces.as_ref().and_then(|published|published.geometry.get(&record.id));
                            let volume=match geometry.map(|space|space.volume){Some(crate::architecture_solver::topology::Volume::Bounded(cells))=>block_junk_mod_api::architecture::GeometryVolume::Bounded{cells},Some(crate::architecture_solver::topology::Volume::Open)=>block_junk_mod_api::architecture::GeometryVolume::Open,_=>block_junk_mod_api::architecture::GeometryVolume::Unknown};
                            receipts.push(CommandReceipt::Space{space:block_junk_mod_api::architecture::SpaceInfo{
                                space_id:*space_id,revision:record.revision,active:record.active,structural_area:record.membership.0.iter().map(|run|u64::from(run.len)).sum(),
                                covered_area:geometry.filter(|space|!space.roofs.values().any(|roof|*roof==crate::architecture_solver::topology::Ceiling::Unknown)).map(|space|space.roofs.values().filter(|roof|matches!(roof,crate::architecture_solver::topology::Ceiling::At(_))).count()as u64),
                                volume,pending:record.active&&(geometry.is_none_or(|space|space.pending)||world.published_spaces.as_ref().is_none_or(|published|!published.pending.is_empty())),
                                predecessors:record.predecessors.len()as u64,successors:record.successors.len()as u64,
                            }});
                        }
                        Command::ReadSpaceLineage{space_id,revision,direction,after_id,limit}=>{
                            if *limit==0||*limit>64{return Err("space lineage page limit must be 1..64".into());}
                            let record=world.spaces.records.get(&crate::space_identity::SpaceId(*space_id)).filter(|record|record.revision==*revision).ok_or("missing or stale space revision")?;
                            let related=match direction{block_junk_mod_api::architecture::LineageDirection::Predecessors=>&record.predecessors,block_junk_mod_api::architecture::LineageDirection::Successors=>&record.successors};
                            let ids:Vec<_>=related.iter().filter(|id|id.0>*after_id).take(usize::from(*limit)+1).map(|id|id.0).collect();
                            let has_more=ids.len()>usize::from(*limit);
                            receipts.push(CommandReceipt::SpaceLineage{space_id:*space_id,revision:*revision,direction:*direction,space_ids:ids.into_iter().take(usize::from(*limit)).collect(),has_more});
                        }
                        Command::ResolveRetiredSpaceState{space_id,state_revision}=>{
                            let id=crate::space_identity::SpaceId(*space_id);
                            let record=world.spaces.records.get(&id).filter(|record|!record.active).ok_or("only retired space state can resolve lineage")?;
                            if record.resolved_state_owners.contains(&batch.mod_id)||!resolved_spaces.insert(id){return Err("space state lineage already resolved".into());}
                            state.remove(StateScope::Space(*space_id),*state_revision)?;
                        }
                        Command::SetPortal { placement_id, revision, key, open } => {
                            let occupied = world.actor_poses.iter().filter(|(entity,_)|!removing.values().any(|removed|removed==entity)).map(|(_,pose)|pose.translation)
                                .chain(spawning.values().map(|(_,position)|*position));
                            crate::portal_service::stage(&mut placements,&mut terrain,crate::portal_service::PortalChange{placement_id:*placement_id,revision:*revision,key,open:*open},&world.blocks,&base,occupied)?;
                        }
                        Command::MovePlacement { placement_id, revision, anchor, orientation } => {
                            let id = block_junk_mod_api::architecture::PlacementId(*placement_id);
                            let record = placements.records.get(&id)
                                .filter(|record| record.active && record.revision == *revision)
                                .cloned().ok_or("placement missing, retired or revision stale")?;
                            let target = IVec3::from_array(*anchor);
                            if record.anchor != *anchor || record.orientation != *orientation {
                                let first_effect = terrain.effects.len();
                                let from = IVec3::from_array(record.anchor);
                                terrain.relocate(from, crate::protocol::BlockEdit {
                                    anchor: target, slot: world.blocks.slot_of(&record.definition).ok_or("placement definition missing")?, orientation: *orientation,
                                }, &world.blocks, &base)?;
                                placements.relocate(id, *revision, target, *orientation, &world.blocks)?;
                                if placements.records[&id].portal_open(&world.blocks).is_some() {
                                    terrain.portal_state(&placements.records[&id], &world.blocks, &base)?;
                                }
                                facilities.relocate(from, target, &world.facilities)?;
                                let jobs: Vec<_> = interaction_jobs.jobs.records.values()
                                    .filter(|job| !job.state.terminal() && matches!(&job.target, block_junk_mod_api::authority::JobTarget::Interaction { slot, .. } if slot.placement == id))
                                    .map(|job| job.id).collect();
                                for job in jobs {
                                    interaction_jobs.finish(job, block_junk_mod_api::authority::JobState::Interrupted, Some("facility moved".into()), &mut interaction_claims);
                                }
                                construction.resolve_terrain(terrain.effects[first_effect..].iter().flat_map(|effect| effect.cells.iter().map(|cell| cell.world)));
                            }
                        }
                        Command::RemovePlacement {
                            placement_id,
                            revision,
                        } => {
                            let record = placements
                                .records
                                .get(&block_junk_mod_api::architecture::PlacementId(
                                    *placement_id,
                                ))
                                .filter(|record| record.active && record.revision == *revision)
                                .ok_or("placement missing, retired or revision stale")?;
                            let first_effect = terrain.effects.len();
                            terrain.stage(
                                crate::protocol::BlockEdit {
                                    anchor: IVec3::from_array(record.anchor),
                                    slot: crate::blocks::BlockSlot::EMPTY,
                                    orientation: record.orientation,
                                },
                                &world.blocks,
                                &base,
                            )?;
                            facilities.retire(
                                &terrain.effects[first_effect..],
                                &world.blocks,
                                &world.facilities,
                            );
                            placements
                                .apply_effects(&terrain.effects[first_effect..], &world.blocks)?;
                            construction.resolve_terrain(
                                terrain.effects[first_effect..]
                                    .iter()
                                    .flat_map(|effect| effect.cells.iter().map(|cell| cell.world)),
                            );
                        }
                        Command::ReadPlacement { cell } => {
                            if cell.iter().any(|v| v.unsigned_abs() > 1_000_000) {
                                return Err("placement query outside supported world".into());
                            }
                            let requested = IVec3::from_array(*cell);
                            let (slot, entry, _) = terrain
                                .read(requested, &base)
                                .ok_or("placement query depends on unavailable geometry")?;
                            let anchor = match entry {
                                Some(crate::voxel::EntryKind::Ghost { anchor }) => anchor,
                                _ => requested,
                            };
                            let (_, entry, _) = terrain
                                .read(anchor, &base)
                                .ok_or("placement anchor unavailable")?;
                            let orientation = match entry {
                                Some(crate::voxel::EntryKind::Anchor { orientation, .. }) => {
                                    orientation
                                }
                                _ => Default::default(),
                            };
                            placements.index_existing(
                                anchor,
                                slot,
                                orientation,
                                &world.blocks,
                                |cell| terrain.read(cell, &base).map(|cell| cell.0),
                            )?;
                            let record = placements.at(requested);
                            let use_slots = record
                                .map(|record| {
                                    world
                                        .blocks
                                        .def(slot)
                                        .facility_slots
                                        .iter()
                                        .map(|slot| block_junk_mod_api::architecture::UseSlotId {
                                            placement: record.id,
                                            key: slot.key.clone(),
                                        })
                                        .collect()
                                })
                                .unwrap_or_default();
                            receipts.push(CommandReceipt::Placement {
                                cell: *cell,
                                placement_id: record.map(|record| record.id.0),
                                revision: record.map(|record| record.revision),
                                use_slots,
                            });
                        }
                        Command::DeliverProject {
                            project_id,
                            revision,
                            npc_id,
                            item,
                            count,
                        } => {
                            if npc_ids.retired.contains(npc_id) {
                                return Err("NPC retired".into());
                            }
                            if *count == 0 {
                                return Err("delivery count must be positive".into());
                            }
                            let anchor = construction.project_anchor(*project_id, *revision)?;
                            let (entity, _, inventory, pose) = world
                                .carriers
                                .iter()
                                .find(|(_, npc, _, _)| npc.0 == *npc_id)
                                .ok_or("delivery actor is unavailable")?;
                            if !pose.translation.is_finite()
                                || pose
                                    .translation
                                    .distance(anchor.as_vec3() + Vec3::splat(0.5))
                                    > crate::protocol::INTERACT_REACH
                            {
                                return Err("delivery actor cannot reach the project".into());
                            }
                            let (_, inventory) =
                                carried.entry(*npc_id).or_insert((entity, *inventory));
                            let expected = world
                                .items
                                .slot_of(&item.clone().into())
                                .ok_or("unknown delivery item")?;
                            if inventory.item != Some(expected) || inventory.count < *count {
                                return Err(
                                    "delivery actor does not hold the requested material bundle"
                                        .into(),
                                );
                            }
                            let accepted =
                                construction.deliver(*project_id, *revision, inventory, *count)?;
                            receipts.push(CommandReceipt::Materials {
                                project_id: *project_id,
                                accepted,
                            });
                        }
                        Command::ReadCell { cell } => {
                            if cell.iter().any(|v| v.unsigned_abs() > 1_000_000) {
                                return Err("query coordinate outside supported world".into());
                            }
                            let (slot, _, revision) = terrain
                                .read(IVec3::from_array(*cell), &base)
                                .ok_or("query depends on unavailable chunk")?;
                            receipts.push(CommandReceipt::Cell {
                                cell: *cell,
                                block: (!slot.is_empty())
                                    .then(|| world.blocks.id_of(slot).as_str().to_owned()),
                                revision,
                            });
                        }
                        Command::EditTerrain {
                            cell,
                            expected_revision,
                            block,
                            orientation,
                        } => {
                            if cell.iter().any(|v| v.unsigned_abs() > 1_000_000) {
                                return Err("edit coordinate outside supported world".into());
                            }
                            let anchor = IVec3::from_array(*cell);
                            let (_, _, revision) = terrain
                                .read(anchor, &base)
                                .ok_or("edit depends on unavailable chunk")?;
                            if revision != *expected_revision {
                                return Err("stale terrain revision".into());
                            }
                            let slot = match block {
                                Some(id) => world
                                    .blocks
                                    .slot_of(&id.clone().into())
                                    .ok_or_else(|| format!("unknown block {id}"))?,
                                None => crate::blocks::BlockSlot::EMPTY,
                            };
                            let first_effect = terrain.effects.len();
                            terrain.stage(
                                crate::protocol::BlockEdit {
                                    anchor,
                                    slot,
                                    orientation: *orientation,
                                },
                                &world.blocks,
                                &base,
                            )?;
                            facilities.retire(
                                &terrain.effects[first_effect..],
                                &world.blocks,
                                &world.facilities,
                            );
                            placements
                                .apply_effects(&terrain.effects[first_effect..], &world.blocks)?;
                            construction.resolve_terrain(
                                terrain.effects[first_effect..]
                                    .iter()
                                    .flat_map(|effect| effect.cells.iter().map(|cell| cell.world)),
                            );
                            let (slot, _, revision) =
                                terrain.read(anchor, &base).expect("staged edited cell");
                            receipts.push(CommandReceipt::Cell {
                                cell: *cell,
                                block: (!slot.is_empty())
                                    .then(|| world.blocks.id_of(slot).as_str().to_owned()),
                                revision,
                            });
                        }
                        Command::Designate {
                            cell,
                            block,
                            orientation,
                        } => {
                            if cell.iter().any(|v| v.unsigned_abs() > 1_000_000) {
                                return Err(
                                    "designation outside supported world coordinates".into()
                                );
                            }
                            let kind = match block {
                                Some(id) => crate::protocol::PlanKind::Build {
                                    slot: world
                                        .blocks
                                        .slot_of(&block_junk_mod_api::blocks::BlockId::new(id))
                                        .ok_or_else(|| format!("unknown block {id}"))?,
                                    orientation: *orientation,
                                },
                                None => crate::protocol::PlanKind::Remove,
                            };
                            let materials = crate::plans::build_initial_materials(
                                kind,
                                &world.blocks,
                                &world.items,
                            );
                            let proposed = crate::protocol::PlanState::new(kind, materials);
                            let (anchor, proposed) = crate::plans::prepare_designation_view(
                                IVec3::from_array(*cell),
                                proposed,
                                &world.blocks,
                                &|cell| {
                                    terrain
                                        .read(cell, &base)
                                        .map(|(slot, entry, _)| (slot, entry))
                                },
                            )
                            .ok_or("designation geometry is unavailable or invalid")?;
                            construction.designate(anchor, proposed)?;
                        }
                        Command::CancelProject {
                            project_id,
                            revision,
                        } => construction.cancel(*project_id, *revision)?,
                        Command::SetState {
                            scope,
                            expected_revision,
                            json,
                        } => {
                            // Durable placement/space identities are introduced with their
                            // owning milestone. Never accept a scope we cannot validate.
                            match scope {
                                StateScope::World => {}
                                StateScope::Space(id) if world.spaces.records.get(&crate::space_identity::SpaceId(*id)).is_some_and(|record|!record.resolved_state_owners.contains(&batch.mod_id)&&!resolved_spaces.contains(&record.id)) => {}
                                StateScope::Placement(id) if placements.contains(*id) => {}
                                StateScope::Npc(id)
                                    if npc_ids.contains(*id)
                                        || world.npcs.iter().any(|npc| npc.0 == *id) => {}
                                _ => {
                                    return Err("missing authoritative state scope identity".into());
                                }
                            }
                            state.set(scope.clone(), *expected_revision, json)?;
                        }
                    }
                }
                if world.effects.0.len() + terrain.effects.len() > 4096 {
                    return Err("terrain publication queue is full".into());
                }
                if serde_json::to_vec(&receipts).map_err(|error|error.to_string())?.len()>block_junk_scripting::commands::MAX_BATCH_BYTES {
                    return Err("command result byte limit exceeded".into());
                }
                let spatial_change=world.facilities.spatial_events.prepare(terrain.changes().map(|(cell,_,_)|cell),batch.cause)?;
                world.facilities.spatial_events.commit_change(spatial_change);
                for id in resolved_spaces {world.spaces.records.get_mut(&id).unwrap().resolved_state_owners.insert(batch.mod_id.clone());}
                world.construction.commit(construction);
                *world.interaction_jobs=interaction_jobs;
                *world.interactions=interaction_claims;
                *world.placements = placements;
                world.facilities.commit(facilities);
                *world.npc_ids = npc_ids;
                for (_, (entity, inventory)) in carried {
                    *world
                        .carriers
                        .get_mut(entity)
                        .expect("validated actor remains borrowed by transaction")
                        .2 = inventory;
                }
                for (id, entity) in removing {
                    world.construction.release_actor(crate::npc::NpcId(id));
                    world.interactions.release_all_for(crate::npc::NpcId(id));
                    if let Ok(mut tool) = world.tools.get_mut(entity) {
                        *tool = Default::default();
                    }
                    world.commands.entity(entity).despawn();
                }
                for (id, (kind, position)) in spawning {
                    crate::npc::spawn_new_npc(
                        &mut world.commands,
                        crate::npc::NpcId(id),
                        world
                            .kind_registry
                            .get(&kind)
                            .expect("validated spawn kind"),
                        position,
                    );
                }
                let effects = crate::server::commit_terrain_geometry(
                    terrain,
                    &mut world.commands,
                    &mut world.chunks,
                    &world.map,
                    &mut world.edits,
                    batch.cause,
                    true,
                );
                world.effects.0.extend(effects);
                Ok(receipts)
            })
        })();
        let receipts = outcome.as_ref().cloned().unwrap_or_default();
        for receipt in &receipts {
            if let CommandReceipt::Job { job } = receipt
                && let Some(cause) = job.cause
            {
                mods.0.pin_cause(cause);
            }
        }
        let result = CommandResult {
            receipts,
            batch_id: batch.id,
            accepted: outcome.is_ok(),
            reason: outcome.err(),
        };
        let mut results = mods.0.commands.results.lock().unwrap();
        let queue = results.entry(batch.mod_id).or_default();
        if queue.len() == 128 {
            queue.pop_front();
        }
        queue.push_back(result);
    }
}
